// Asosiy til — o'zbekcha; tanlangan til brauzerda eslab qolinadi
let lang = 'uz';
try { lang = localStorage.getItem('hm-lang') || 'uz'; } catch { /* private mode */ }
if (!DICT[lang]) lang = 'uz';

const listeners = new Set();
export const getLang = () => lang;
export const t = (key) => DICT[lang][key] ?? DICT.uz[key] ?? key;
export const onLang = (fn) => { listeners.add(fn); return () => listeners.delete(fn); };

export function applyI18n(root = document) {
  document.documentElement.lang = lang;
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll('[data-lang]').forEach((el) => {
    el.classList.toggle('is-active', el.dataset.lang === lang);
    el.setAttribute('aria-pressed', String(el.dataset.lang === lang));
  });
}

export function setLang(next) {
  if (!DICT[next] || next === lang) return;
  lang = next;
  try { localStorage.setItem('hm-lang', lang); } catch { /* ignore */ }
  applyI18n();
  listeners.forEach((fn) => fn(lang));
}
